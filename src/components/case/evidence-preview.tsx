import { Download } from "lucide-react";
import { useState } from "react";
import { cn } from "#/lib/utils";
import { Button } from "../ui/button";
import {
	Sheet,
	SheetContent,
	SheetDescription,
	SheetHeader,
	SheetTitle,
} from "../ui/sheet";
import type { DisputeDetail } from "./types";

