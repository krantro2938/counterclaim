import { Download, FileText } from "lucide-react";
import { useState } from "react";
import { Button } from "../ui/button";
import {
	Sheet,
	SheetContent,
	SheetDescription,
	SheetHeader,
	SheetTitle,
} from "../ui/sheet";
import type { DisputeDetail } from "./types";

/** Evidence packet: thumbnail on the case page, full PDF in a side sheet. */
export function EvidencePreview({ detail }: { detail: DisputeDetail }) {
	const [open, setOpen] = useState(false);
	const sent = detail.evidenceFiles[0];
	const hasEvidenceAction = detail.actions.some(
		(a) => a.type === "provide_evidence",
	);
	if (!sent && !hasEvidenceAction) return null;
	const src = sent
		? `/api/evidence/${sent.id}.pdf`
		: `/api/disputes/${detail.dispute.id}/evidence-preview`;
	return (
		<section aria-label="Evidence" className="rounded-lg border bg-card p-4">
			<button
				type="button"
				onClick={() => setOpen(true)}
				className="flex w-full items-center gap-3 text-left"
			>
				<span className="flex h-16 w-12 shrink-0 flex-col items-center justify-center rounded border bg-background shadow-sm">
					<FileText className="size-5 text-primary" />
					<span className="mt-1 font-mono text-[9px] text-muted-foreground">
						PDF
					</span>
				</span>
				<span className="min-w-0">
					<span className="block font-medium">
						{sent ? "Evidence packet sent" : "Draft evidence packet"}
					</span>
					<span className="block truncate font-mono text-xs text-muted-foreground">
						{sent
							? `${sent.filename} · ${(sent.sizeBytes / 1024).toFixed(0)} KB`
							: `evidence-${detail.dispute.id}.pdf`}
					</span>
					<span className="text-xs text-primary">Preview →</span>
				</span>
			</button>
			<Sheet open={open} onOpenChange={setOpen}>
				<SheetContent side="right" className="w-full gap-0 sm:max-w-[720px]">
					<SheetHeader>
						<SheetTitle>
							{sent
								? "Evidence packet (as sent to PayPal)"
								: "Draft evidence packet"}
						</SheetTitle>
						<SheetDescription>
							Generated by Counterclaim from the case file. Carrier events from
							the sandbox simulator are marked.
						</SheetDescription>
					</SheetHeader>
					<div className="flex-1 px-4 pb-4">
						{open && (
							<iframe
								title="Evidence PDF"
								src={src}
								className="h-[calc(100vh-170px)] w-full rounded border"
							/>
						)}
						<Button
							asChild
							variant="outline"
							size="sm"
							className="mt-3 gap-1.5"
						>
							<a href={sent ? `${src}?download` : src} download>
								<Download className="size-3.5" /> Download PDF
							</a>
						</Button>
					</div>
				</SheetContent>
			</Sheet>
		</section>
	);
}
