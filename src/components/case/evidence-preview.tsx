/** Evidence packet: thumbnail on the case page, full PDF in a side sheet. */
export function EvidencePreview({ detail }: { detail: DisputeDetail }) {
	const [open, setOpen] = useState(false);
	// Only a packet whose action PayPal accepted counts as sent; a failed attempt is still a draft.
	const sent = detail.evidenceFiles.find((f) =>
		detail.actions.some((a) => a.id === f.actionId && a.status === "succeeded"),
	);
	const hasEvidenceAction = detail.actions.some(
		(a) => a.type === "provide_evidence",
	);
	if (!sent && !hasEvidenceAction) return null;
	const src = sent
		? `/api/evidence/${sent.id}.pdf`
		: `/api/disputes/${detail.dispute.id}/evidence-preview`;
	return (
		<section aria-label="Evidence" className="field p-5">
			<button
				type="button"
				onClick={() => setOpen(true)}
				className="flex w-full items-center gap-4 text-left"
			>
				<PdfIcon />
				<span className="min-w-0">
					<span className="block font-medium">
						{sent ? "Evidence packet sent" : "Draft evidence packet"}
					</span>
					<span className="block truncate text-xs text-muted-foreground">
						{sent
							? `${sent.filename} · ${(sent.sizeBytes / 1024).toFixed(0)} KB`
							: `evidence-${detail.dispute.id}.pdf`}
					</span>
					<span className="text-xs font-medium text-primary">Preview</span>
				</span>
			</button>
			<Sheet open={open} onOpenChange={setOpen}>
				<SheetContent side="right" className="w-full gap-0 sm:max-w-[720px]">
					<SheetHeader>
						<SheetTitle>
							{sent
								? "Evidence packet (as sent to PayPal)"
								: "Draft evidence packet"}
						</SheetTitle>
						<SheetDescription>
							Generated by Counterclaim from the case file. Carrier events from
							the sandbox simulator are marked.
						</SheetDescription>
					</SheetHeader>
					<div className="flex-1 px-4 pb-4">
						{open && (
							<iframe
								title="Evidence PDF"
								src={src}
								className="h-[calc(100vh-170px)] w-full rounded-lg bg-muted"
							/>
						)}
						<Button
							asChild
							variant="outline"
							size="sm"
							className="mt-3 gap-1.5"
						>
							<a href={sent ? `${src}?download` : src} download>
								<Download className="size-3.5" /> Download PDF
							</a>
						</Button>
					</div>
				</SheetContent>
			</Sheet>
		</section>
	);
}
