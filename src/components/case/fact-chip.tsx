import { Mail, Package, Store, Wallet } from "lucide-react";
import { cn } from "#/lib/utils";
import {
	HoverCard,
	HoverCardContent,
	HoverCardTrigger,
} from "../ui/hover-card";
import type { FactDto } from "./types";

const SOURCE: Record<
	string,
	{ label: string; Icon: React.ComponentType<{ className?: string }> }
> = {
	paypal: { label: "PayPal", Icon: Wallet },
	carrier_sim: { label: "Carrier (simulated)", Icon: Package },
	store: { label: "Your store", Icon: Store },
	messages: { label: "Messages", Icon: Mail },
};

/** Inline citation pill. Every AI claim links to a fact (DESIGN principle 2). */
export function FactChip({ id, facts }: { id: string; facts: FactDto[] }) {
	const f = facts.find((x) => x.id === id);
	const pp = id.startsWith("PP:");
	const src = f ? SOURCE[f.source] : SOURCE.paypal;
	const chip = (
		<button
			type="button"
			className={cn(
				"inline-flex h-5 items-center gap-1 rounded-full border bg-card px-1.5 align-middle font-mono text-[11px] text-muted-foreground transition-colors hover:border-primary hover:text-foreground",
				f?.simulated && "border-simulated/40",
			)}
			aria-label={`Fact ${id}`}
		>
			<src.Icon className="size-3" />
			{pp ? id.split(":")[1] : id}
			{f?.simulated && (
				<span
					className="size-1.5 rounded-full bg-simulated"
					aria-label="simulated"
				/>
			)}
		</button>
	);
	return (
		<HoverCard openDelay={120}>
			<HoverCardTrigger asChild>{chip}</HoverCardTrigger>
			<HoverCardContent className="w-80 text-sm" side="top">
				<div className="mb-1 flex items-center gap-1.5 text-xs text-muted-foreground">
					<src.Icon className="size-3.5" />
					{pp ? "PayPal Agent Toolkit (live read)" : src.label}
					<span className="ml-auto font-mono">{id}</span>
				</div>
				<p>
					{f
						? f.text
						: pp
							? `Value read live from PayPal via ${id.split(":")[1]}: ${id.split(":").slice(2).join(":")}`
							: "Unknown fact"}
				</p>
				{f?.simulated && (
					<p className="mt-1 text-xs text-simulated">
						Generated by the sandbox carrier simulator.
					</p>
				)}
			</HoverCardContent>
		</HoverCard>
	);
}
